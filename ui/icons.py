def icone(nom: str, couleur: str, taille: int = 20) -> QIcon:
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="%s" '
           'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">%s</svg>' % (couleur, _CORPS[nom]))
    rendu = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    pm = QPixmap(taille * 2, taille * 2)  # x2 pour les écrans HiDPI
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    rendu.render(p)
    p.end()
    pm.setDevicePixelRatio(2)
    return QIcon(pm)
